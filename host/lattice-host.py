#!/usr/bin/env python3
"""Run the real Lattice on a Linux host and reach it from other devices.

Lattice's own Linux AppImage runs in browser-host mode on a private virtual
display. lattice-gateway sits in front of it and decides who may connect.
This tool installs a pinned Lattice release, writes three systemd user
services, and updates or rolls back the release.

    lattice-host install --public-origin https://workspace.example.ts.net
    lattice-host status
    lattice-host update --to 0.19.0
    lattice-host rollback
    lattice-host phone
    lattice-host check-update
    lattice-host uninstall
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
import urllib.request
from pathlib import Path

KIT = Path(__file__).resolve().parent
DEFAULT_ROOT = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share")) / "lattice-host"
UNIT_DIR = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "systemd/user"
UNITS = ("lattice-display.service", "lattice-browser-host.service", "lattice-gateway.service")
LATTICE_PORT = 18452  # Fixed by Lattice: src-tauri/src/browser_host.rs PREFERRED_PORT.
KEEP_RELEASES = 3
# The owner's update prompt: a timer looks for a newer stable kit, a path unit
# looks again when the owner selects Check now in the browser, and another
# runs the update when the owner selects Update.
UPDATE_UNITS = ("lattice-update-check.timer", "lattice-update-check.path", "lattice-update.path")
UPDATE_FILES = ("lattice-update-check.service", "lattice-update-check.timer", "lattice-update-check.path", "lattice-update.path", "lattice-update.service")
UPDATE_REPO = "lattice-writer/lattice-web-ui"
KEEP_KITS = 2
VERSION_RE = re.compile(r"\d{1,6}\.\d{1,6}\.\d{1,6}")

# Lattice hands "open this workspace in a browser" to xdg-open. On a headless
# host there is no browser to open, so the address is dropped where the
# gateway can pass it to the tab that asked. Anything else is ignored.
OPENER = """#!/bin/sh
# Generated by lattice-host: forwards Lattice's browser-entry addresses to lattice-gateway.
case "$1" in
  http://127.0.0.1:18452/\\?entry=*) ;;
  @PUBLIC@/__gateway/devices) ;;
  *) exit 0 ;;
esac
spool='@SPOOL@'
name="$(date +%s%N).$$"
umask 077
printf '%s\\n' "$1" > "$spool/.$name" && mv "$spool/.$name" "$spool/$name.url"
exit 0
"""

# The rewrites lattice-gateway makes in Lattice's page (gateway/src/bridge.rs),
# counted here over every script the page can load.
REWRITE_RULES = {
    "http": r"http://127\.0\.0\.1:\$\{[^}`]+\}",
    "ws": r"ws://127\.0\.0\.1:\$\{[^}`]+\}",
    "protocol": r"window\.location\.protocol===`http:`",
    "hostname": r"window\.location\.hostname===`127\.0\.0\.1`",
    "port": r"window\.location\.port===[A-Za-z_$][\w$]*",
}


class HostError(Exception):
    """A step failed in a way the user can act on."""


def say(message: str) -> None:
    print(f"lattice-host: {message}", flush=True)


def load_manifest(path: Path) -> dict:
    data = json.loads(path.read_text())
    releases = {entry["version"]: entry for entry in data["releases"]}
    if data["default"] not in releases:
        raise HostError(f"{path}: the default release {data['default']} is not listed.")
    for entry in releases.values():
        if len(entry["sha256"]) != 64 or not entry["url"].startswith(("https://", "file://")):
            raise HostError(f"{path}: release {entry['version']} needs an https:// (or local file://) URL and a sha256.")
    return {"default": data["default"], "releases": releases}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def download(url: str, target: Path, expected_sha256: str) -> None:
    if url.startswith("file://"):
        shutil.copyfile(url[len("file://"):], target)
    else:
        say(f"downloading {url}")
        request = urllib.request.Request(url, headers={"User-Agent": "lattice-host"})
        with urllib.request.urlopen(request, timeout=120) as response, target.open("wb") as out:
            shutil.copyfileobj(response, out, 1 << 20)
    actual = sha256_file(target)
    if actual != expected_sha256:
        target.unlink(missing_ok=True)
        raise HostError(f"checksum mismatch for {url}: expected {expected_sha256}, got {actual}. Nothing was installed.")


def stage_release(root: Path, entry: dict) -> Path:
    """Download, verify and extract one release. Idempotent."""
    release_dir = root / "releases" / entry["version"]
    app_run = release_dir / "squashfs-root" / "AppRun"
    if app_run.exists():
        return release_dir
    release_dir.parent.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix=f".{entry['version']}-", dir=release_dir.parent))
    try:
        image = work / "Lattice.AppImage"
        download(entry["url"], image, entry["sha256"])
        image.chmod(0o755)
        # No FUSE needed: extract the image instead of mounting it.
        subprocess.run([str(image), "--appimage-extract"], cwd=work, check=True, stdout=subprocess.DEVNULL)
        image.unlink()
        if not (work / "squashfs-root" / "AppRun").exists():
            raise HostError(f"{entry['url']} did not extract to an AppImage with AppRun.")
        (work / "release.json").write_text(json.dumps(entry, indent=2) + "\n")
        work.rename(release_dir)
    finally:
        if work.exists():
            shutil.rmtree(work, ignore_errors=True)
    return release_dir


def current_version(root: Path) -> str | None:
    link = root / "current"
    return Path(os.readlink(link)).name if link.is_symlink() else None


def point(root: Path, name: str, version: str) -> None:
    link = root / name
    temp = root / f".{name}.new"
    temp.unlink(missing_ok=True)
    temp.symlink_to(Path("releases") / version)
    temp.replace(link)


def find_xvfb(root: Path, given: str | None) -> Path:
    for candidate in [given, shutil.which("Xvfb"), root / "xvfb/usr/bin/Xvfb"]:
        if candidate and Path(candidate).is_file() and os.access(candidate, os.X_OK):
            return Path(candidate)
    raise HostError("Xvfb is not installed. Run `sudo apt install xvfb`, or rerun with --fetch-xvfb to unpack it into the host directory without sudo.")


def fetch_xvfb(root: Path) -> Path:
    """Unpack Ubuntu's xvfb package into the host directory, without root."""
    target = root / "xvfb"
    with tempfile.TemporaryDirectory() as temp:
        subprocess.run(["apt", "download", "xvfb"], cwd=temp, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        debs = glob.glob(f"{temp}/*.deb")
        if not any(Path(deb).name.startswith("xvfb_") for deb in debs):
            raise HostError("apt download xvfb produced no package.")
        target.mkdir(parents=True, exist_ok=True)
        for deb in debs:
            subprocess.run(["dpkg", "-x", deb, str(target)], check=True)
    binary = target / "usr/bin/Xvfb"
    missing = [line for line in subprocess.run(["ldd", str(binary)], capture_output=True, text=True).stdout.splitlines() if "not found" in line]
    if missing:
        raise HostError("Xvfb needs libraries this host lacks: " + "; ".join(m.strip() for m in missing))
    return binary


def hidden_under_home(path: Path, home: Path) -> bool:
    """True for a path below a dot-folder of HOME, where Lattice's Agent will not run."""
    try:
        relative = path.expanduser().resolve().relative_to(home.resolve())
    except ValueError:
        return False
    return any(part.startswith(".") for part in relative.parts)



def find_tlmgr(home: Path) -> str | None:
    """tlmgr of a TeX tree the host user can write to (TinyTeX, or TeX Live in user mode)."""
    candidates = [shutil.which("tlmgr")] + sorted(glob.glob(str(home / ".TinyTeX/bin/*/tlmgr")))
    for candidate in filter(None, candidates):
        real = Path(candidate).resolve()
        tree = next((parent for parent in real.parents if (parent / "texmf-dist").is_dir()), None)
        if tree and os.access(tree, os.W_OK) and os.access(tree / "texmf-dist", os.W_OK):
            # tlmgr finds its tree from the bin/<platform>/tlmgr it is started as.
            launchers = sorted(glob.glob(str(tree / "bin/*/tlmgr")))
            return launchers[0] if launchers else candidate
    return None



def tool_path(home: Path) -> str:
    """PATH for Lattice: its no-op opener first, then TeX and the user's CLIs."""
    parts: list[str] = []
    for tool in ("latexmk", "pdflatex", "git", "claude", "codex"):
        found = shutil.which(tool)
        if found:
            parts.append(str(Path(found).parent))
    parts += sorted(glob.glob(str(home / ".TinyTeX/bin/*"))) + sorted(glob.glob("/usr/local/texlive/*/bin/*"))
    parts += [str(home / ".local/bin"), "/usr/local/bin", "/usr/bin", "/bin"]
    seen: list[str] = []
    for part in parts:
        if part not in seen:
            seen.append(part)
    return ":".join(seen)


def write_files(root: Path, config: dict) -> None:
    """The launcher, the no-op opener and the three systemd units."""
    bin_dir = root / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    state = root / "state" / "lattice"
    for sub in ("config", "data", "cache", "state", "runtime"):
        (state / sub).mkdir(parents=True, exist_ok=True)
    (state / "runtime").chmod(0o700)

    spool = root / "state" / "open-requests"
    spool.mkdir(parents=True, exist_ok=True)
    spool.chmod(0o700)
    opener = bin_dir / "xdg-open"
    opener.write_text(OPENER.replace("@SPOOL@", str(spool)).replace("@PUBLIC@", config["public_origin"]))
    opener.chmod(0o755)
    # The AppImage's launcher puts its own usr/bin first on PATH, so its
    # bundled xdg-open is replaced in every staged release as well.
    for release in (root / "releases").glob("*/squashfs-root/usr/bin"):
        bundled = release / "xdg-open"
        if bundled.exists() or bundled.is_symlink():
            bundled.unlink()
        shutil.copy2(opener, bundled)

    env = {
        "HOME": config["home"],
        "XDG_CONFIG_HOME": str(state / "config"),
        "XDG_DATA_HOME": str(state / "data"),
        "XDG_CACHE_HOME": str(state / "cache"),
        "XDG_STATE_HOME": str(state / "state"),
        "XDG_RUNTIME_DIR": str(state / "runtime"),
        "DISPLAY": f":{config['display']}",
        "BROWSER": "/bin/true",
        "PATH": f"{bin_dir}:{config['path']}",
        "LANG": config.get("lang", "en_US.UTF-8"),
        "USER": config["user"],
        "LOGNAME": config["user"],
        "SHELL": config.get("shell", "/bin/bash"),
        "TERM": "xterm-256color",
        "WEBKIT_DISABLE_COMPOSITING_MODE": "1",
    }
    lines = ["#!/bin/sh", "# Generated by lattice-host. A scrubbed environment keeps Lattice off the desktop session.", "exec env -i \\"]
    lines += [f"  {key}={shell_quote(value)} \\" for key, value in env.items()]
    lines += [f"  dbus-run-session -- {shell_quote(str(root / 'current/squashfs-root/AppRun'))} --browser-host"]
    launcher = bin_dir / "run-lattice"
    launcher.write_text("\n".join(lines) + "\n")
    launcher.chmod(0o755)

    gateway_args = [
        str(bin_dir / "lattice-gateway"),
        "--listen", f"127.0.0.1:{config['gateway_port']}",
        "--public-origin", config["public_origin"],
        "--upstream", f"127.0.0.1:{LATTICE_PORT}",
        "--state-dir", str(root / "state" / "gateway"),
        "--token-file", str(root / "access-token"),
        "--open-requests", str(root / "state" / "open-requests"),
    ]
    if config.get("rewrite_page"):
        gateway_args.append("--rewrite-loopback-page")
    if config.get("projects_root"):
        gateway_args += ["--projects-root", config["projects_root"]]
    if config.get("agent_origin"):
        gateway_args += ["--agent-listen", f"127.0.0.1:{config['gateway_port'] + 1}",
                         "--agent-origin", config["agent_origin"],
                         "--agent-process-marker", str(root / "releases")]
    if config.get("tlmgr"):
        gateway_args += ["--tlmgr", config["tlmgr"]]
    updates = (root / "kit").is_symlink()
    if updates:
        gateway_args += ["--update-dir", str(update_dir(root))]
    if config.get("tailscale"):
        # Tailscale Serve/Funnel hands connections to these sockets; on the tailnet the
        # owner's login is recognised, from the internet people pair or sign in.
        gateway_args += ["--serve-socket", str(root / "serve.sock"), "--owner-logins", str(root / "owner-logins")]
        if config.get("agent_origin"):
            gateway_args += ["--agent-serve-socket", str(root / "agent.sock")]
        if config.get("ingress_uid") is not None:
            gateway_args += ["--ingress-uid", str(config["ingress_uid"])]

    UNIT_DIR.mkdir(parents=True, exist_ok=True)
    units = {
        "lattice-display.service": f"""[Unit]
Description=Lattice private virtual display :{config['display']}

[Service]
ExecStart={config['xvfb']} :{config['display']} -screen 0 1920x1080x24 -nolisten tcp -noreset
Restart=on-failure

[Install]
WantedBy=default.target
""",
        "lattice-browser-host.service": f"""[Unit]
Description=Lattice {config['version']} in browser-host mode
Requires=lattice-display.service
After=lattice-display.service

[Service]
ExecStartPre=/bin/sh -c 'for i in $(seq 50); do [ -S /tmp/.X11-unix/X{config['display']} ] && exit 0; sleep 0.1; done; exit 1'
ExecStart={bin_dir / 'run-lattice'}
KillMode=control-group
Restart=on-failure
RestartSec=3

[Install]
WantedBy=default.target
""",
        "lattice-gateway.service": f"""[Unit]
Description=Lattice access gateway for {config['public_origin']}
After=lattice-browser-host.service

[Service]
ExecStart={' '.join(shell_quote(a) for a in gateway_args)}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
""",
    }
    if updates:
        tool = f"/usr/bin/env python3 {shell_quote(str(root / 'kit/lattice-host'))} --root {shell_quote(str(root))}"
        units.update({
            "lattice-update-check.service": f"""[Unit]
Description=Look for a newer stable lattice-web-ui release

[Service]
Type=oneshot
ExecStart={tool} check-update
""",
            "lattice-update-check.timer": """[Unit]
Description=Look for a newer stable lattice-web-ui release every six hours

[Timer]
OnBootSec=5min
OnUnitActiveSec=6h
RandomizedDelaySec=10min
Persistent=true

[Install]
WantedBy=timers.target
""",
            "lattice-update-check.path": f"""[Unit]
Description=Look for a newer lattice-web-ui release when the owner asks from the browser

[Path]
PathExists={update_dir(root) / 'check'}
Unit=lattice-update-check.service

[Install]
WantedBy=default.target
""",
            "lattice-update.path": f"""[Unit]
Description=Update lattice-web-ui when the owner asks from the browser

[Path]
PathExists={update_dir(root) / 'request'}
Unit=lattice-update.service

[Install]
WantedBy=default.target
""",
            "lattice-update.service": f"""[Unit]
Description=Update lattice-web-ui to the release the owner chose

[Service]
Type=oneshot
TimeoutStartSec=20min
ExecStart={tool} self-update
""",
        })
    for name, text in units.items():
        (UNIT_DIR / name).write_text(text)


def install_gateway(root: Path, source: Path) -> bool:
    """Put the gateway binary in place atomically, so a running one is never overwritten. True if it changed."""
    target = root / "bin/lattice-gateway"
    if target.exists() and sha256_file(target) == sha256_file(source):
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_name(f".lattice-gateway.{os.getpid()}")
    shutil.copy2(source, temp)
    temp.chmod(0o755)
    temp.replace(target)
    return True


def shell_quote(value: str) -> str:
    if value and all(c.isalnum() or c in "/._-:=@+," for c in value):
        return value
    return "'" + value.replace("'", "'\\''") + "'"


def systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["systemctl", "--user", *args], check=check, capture_output=True, text=True)


def lattice_healthy(timeout: float = 90.0, port: int = LATTICE_PORT) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            request = urllib.request.Request(f"http://127.0.0.1:{port}/", headers={"Host": f"127.0.0.1:{port}"})
            with urllib.request.urlopen(request, timeout=3) as response:
                if response.status == 200:
                    return True
        except OSError:
            pass
        time.sleep(1)
    return False


def page_rewrite_counts(port: int = LATTICE_PORT) -> dict:
    """Count the gateway's rewrites over every script Lattice's page can load."""
    import re
    def get(path: str) -> str:
        request = urllib.request.Request(f"http://127.0.0.1:{port}{path}", headers={"Host": f"127.0.0.1:{port}"})
        with urllib.request.urlopen(request, timeout=10) as response:
            return response.read().decode("utf-8", "replace")
    rules = {name: re.compile(pattern) for name, pattern in REWRITE_RULES.items()}
    counts = {name: 0 for name in rules}
    todo = re.findall(r'(?:src|href)="(/[^"]+\.js)"', get("/"))
    seen: set[str] = set()
    while todo and len(seen) < 5000:
        path = todo.pop()
        if path in seen:
            continue
        seen.add(path)
        text = get(path)
        for name, rule in rules.items():
            counts[name] += len(rule.findall(text))
        todo += [f"/assets/{name}" for name in re.findall(r'["`]\./([A-Za-z0-9_.-]+\.js)["`]', text)]
    return counts


def verify_page(entry: dict) -> None:
    """A pinned release lists the rewrites its page needs; anything else is refused."""
    expected = entry.get("frontendRewrite")
    if not expected:
        return
    actual = page_rewrite_counts()
    if actual != expected:
        raise HostError(f"Lattice {entry['version']}'s page does not match what this kit was tested with "
                        f"(rewrites expected {expected}, found {actual}). Use a kit made for this Lattice release.")


def config_path(root: Path) -> Path:
    return root / "host.json"


def read_config(root: Path) -> dict:
    path = config_path(root)
    if not path.exists():
        raise HostError(f"no installation at {root}. Run `lattice-host install` first.")
    return json.loads(path.read_text())


def save_config(root: Path, config: dict) -> None:
    path = config_path(root)
    path.write_text(json.dumps(config, indent=2) + "\n")
    path.chmod(0o600)


def prune(root: Path) -> None:
    keep = {current_version(root)}
    previous = root / "previous"
    if previous.is_symlink():
        keep.add(Path(os.readlink(previous)).name)
    releases = sorted((root / "releases").iterdir(), key=lambda p: p.stat().st_mtime, reverse=True)
    for release in releases[KEEP_RELEASES:]:
        if release.name not in keep and not release.name.startswith("."):
            shutil.rmtree(release, ignore_errors=True)


def kit_version(kit: Path) -> str | None:
    """The lattice-web-ui version of an unpacked kit; None for a source checkout."""
    try:
        version = (kit / "release-version.txt").read_text().strip()
    except OSError:
        return None
    return version if VERSION_RE.fullmatch(version) else None


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def adopt_kit(root: Path, config: dict) -> bool:
    """Keep the kit being installed in the host directory, so that the host
    can later update itself from the browser. A source checkout is not kept."""
    version = kit_version(KIT)
    if not version:
        return False
    kits = root / "kits"
    kits.mkdir(parents=True, exist_ok=True)
    target = kits / version
    if KIT.resolve() != target.resolve():
        temp = kits / f".{version}.{os.getpid()}"
        shutil.rmtree(temp, ignore_errors=True)
        shutil.copytree(KIT, temp, symlinks=True)
        shutil.rmtree(target, ignore_errors=True)
        temp.rename(target)
    link = root / "kit"
    temp_link = root / ".kit.new"
    temp_link.unlink(missing_ok=True)
    temp_link.symlink_to(Path("kits") / version)
    temp_link.replace(link)
    config["manifest"] = str(target / "lattice-releases.json")
    return True


def prune_kits(root: Path) -> None:
    kits = root / "kits"
    current = Path(os.readlink(root / "kit")).name if (root / "kit").is_symlink() else None
    versions = sorted((k.name for k in kits.iterdir() if VERSION_RE.fullmatch(k.name)), key=version_key, reverse=True)
    kept = [v for v in versions if v == current] + [v for v in versions if v != current][: KEEP_KITS - 1]
    for version in versions:
        if version not in kept:
            shutil.rmtree(kits / version, ignore_errors=True)


def update_dir(root: Path) -> Path:
    path = root / "state" / "update"
    path.mkdir(parents=True, exist_ok=True)
    path.chmod(0o700)
    return path


def write_private_json(path: Path, value: dict) -> None:
    temp = path.with_name(f".{path.name}.{os.getpid()}")
    temp.write_text(json.dumps(value, indent=2) + "\n")
    temp.chmod(0o600)
    temp.replace(path)


def enable_update_units(root: Path) -> None:
    if (root / "kit").is_symlink():
        systemctl("enable", "--now", *UPDATE_UNITS)


def releases_api(repo: str) -> str:
    # Tests point this at a local server.
    return os.environ.get("LATTICE_HOST_RELEASES_API") or f"https://api.github.com/repos/{repo}"


def fetch(url: str, limit: int = 4 << 20) -> bytes:
    if not url.startswith("https://") and not os.environ.get("LATTICE_HOST_RELEASES_API"):
        raise HostError(f"refusing to fetch {url}: only https:// addresses are used.")
    request = urllib.request.Request(url, headers={"User-Agent": "lattice-host", "Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read(limit)


def gateway_version(port: int) -> str | None:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/__gateway/health", timeout=3) as response:
            return json.loads(response.read(1 << 16)).get("version")
    except (OSError, ValueError):
        return None


def switch_to(root: Path, version: str, start: bool, entry: dict) -> None:
    old = current_version(root)
    if old and old != version:
        point(root, "previous", old)
    point(root, "current", version)
    config = read_config(root)
    config["version"] = version
    config["rewrite_page"] = bool(entry.get("frontendRewrite"))
    save_config(root, config)
    write_files(root, config)
    if not start:
        return
    systemctl("daemon-reload")
    systemctl("restart", "lattice-browser-host.service", "lattice-gateway.service")
    problem = None
    if lattice_healthy():
        try:
            verify_page(entry)
            say(f"Lattice {version} is serving on 127.0.0.1:{LATTICE_PORT}.")
            return
        except HostError as error:
            problem = str(error)
    if problem:
        say(problem)
    if old and old != version:
        say(f"Lattice {version} did not come up; going back to {old}.")
        point(root, "current", old)
        config["version"] = old
        save_config(root, config)
        write_files(root, config)
        systemctl("daemon-reload")
        systemctl("restart", "lattice-browser-host.service", "lattice-gateway.service")
        healthy = lattice_healthy()
        raise HostError(f"update to {version} failed and was rolled back to {old}" + ("" if healthy else f", which is not healthy either. See `journalctl --user -u lattice-browser-host`") + ".")
    raise HostError(f"Lattice {version} did not start. See `journalctl --user -u lattice-browser-host`.")


def cmd_install(args: argparse.Namespace) -> None:
    root: Path = args.root
    manifest = load_manifest(args.manifest)
    version = args.version or manifest["default"]
    if version not in manifest["releases"]:
        raise HostError(f"Lattice {version} is not in {args.manifest}. Listed: {', '.join(manifest['releases'])}.")
    if args.tailscale and not args.owner_login:
        raise HostError("--tailscale needs at least one --owner-login: the Tailscale login that is the owner, e.g. you@github.")
    root.mkdir(parents=True, exist_ok=True)
    root.chmod(0o700)
    gateway = Path(args.gateway_binary or KIT / "bin/lattice-gateway")
    if not gateway.is_file():
        raise HostError(f"{gateway} is missing. Build it with `cargo build --release --manifest-path gateway/Cargo.toml` or use the host kit from a release.")
    xvfb = fetch_xvfb(root) if args.fetch_xvfb else find_xvfb(root, args.xvfb)
    install_gateway(root, gateway)
    if args.owner_login:
        logins = root / "owner-logins"
        logins.write_text("".join(f"{login}\n" for login in args.owner_login))
        logins.chmod(0o600)
    home = Path(args.home).expanduser() if args.home else Path.home()
    config = {
        "version": version,
        "public_origin": args.public_origin,
        "tailscale": args.tailscale,
        "ingress_uid": args.ingress_uid,
        "gateway_port": args.gateway_port,
        "display": args.display,
        "xvfb": str(xvfb),
        "home": str(home),
        "user": os.environ.get("USER") or Path.home().name,
        "path": tool_path(home),
        "manifest": str(args.manifest.resolve()),
        "rewrite_page": bool(manifest["releases"][version].get("frontendRewrite")),
        "projects_root": str(Path(args.projects_root).expanduser()) if args.projects_root else None,
        "agent_origin": args.agent_origin,
        "shell": os.environ.get("SHELL") or "/bin/bash",
    }
    if config["projects_root"] and hidden_under_home(Path(config["projects_root"]), home):
        say("the projects folder is inside a hidden folder of your home. Lattice's Agent refuses projects there "
            "(it cannot protect their .bib files); move them to an ordinary folder such as ~/lattice-projects.")
    config["tlmgr"] = find_tlmgr(home)
    if not config["tlmgr"]:
        say("No TeX installation this user can write to, so the gateway will not install TeX packages. Install missing packages with your distribution.")
    adopt_kit(root, config)
    save_config(root, config)
    stage_release(root, manifest["releases"][version])
    point(root, "current", version)
    write_files(root, config)
    if args.no_start:
        say("installed; services written but not started (--no-start).")
        return
    systemctl("daemon-reload")
    systemctl("enable", "--now", *UNITS)
    enable_update_units(root)
    # Re-running install changes settings: the gateway picks them up on restart.
    systemctl("restart", "lattice-display.service", "lattice-browser-host.service", "lattice-gateway.service")
    if not lattice_healthy():
        raise HostError("Lattice did not start. See `journalctl --user -u lattice-browser-host`.")
    verify_page(manifest["releases"][version])
    say(f"Lattice {version} is running. Gateway: http://127.0.0.1:{args.gateway_port} for {args.public_origin}")
    say(f"Owner token: {root / 'access-token'} (sign in at {args.public_origin}/__gateway/login)")
    if not args.tailscale:
        say(f"Put HTTPS in front of http://127.0.0.1:{args.gateway_port} (Caddy: examples/Caddyfile).")
    if args.tailscale:
        say(f"Public on the internet: tailscale funnel --bg --https=8443 unix:{root / 'serve.sock'}")
        say("  (or tailnet only: tailscale serve --bg --https=<port> unix:...). Funnel allows ports 443, 8443 and 10000.")
    if args.agent_origin:
        target = f"unix:{root / 'agent.sock'}" if args.tailscale else f"http://127.0.0.1:{args.gateway_port + 1}"
        say(f"Agent: tailscale funnel --bg --https=<port of {args.agent_origin}> {target}")
    show_phone(root, config)


def cmd_update(args: argparse.Namespace) -> None:
    root: Path = args.root
    config = read_config(root)
    # A newer kit brings its own pins and gateway; prefer them over the installed ones.
    manifest_path = Path(args.manifest) if args.manifest else KIT / "lattice-releases.json"
    if not manifest_path.exists():
        manifest_path = Path(config["manifest"])
    manifest = load_manifest(manifest_path)
    if str(manifest_path.resolve()) != config["manifest"]:
        config["manifest"] = str(manifest_path.resolve())
        save_config(root, config)
    if adopt_kit(root, config):
        save_config(root, config)
    kit_gateway = Path(args.gateway_binary) if args.gateway_binary else KIT / "bin/lattice-gateway"
    if kit_gateway.is_file() and install_gateway(root, kit_gateway):
        say("installed this kit's lattice-gateway.")
    # This kit's services may differ from the installed ones (new gateway options, update units).
    write_files(root, config)
    if not args.no_start:
        systemctl("daemon-reload")
        enable_update_units(root)
        systemctl("restart", "lattice-gateway.service")
    version = args.to or manifest["default"]
    if version not in manifest["releases"]:
        raise HostError(f"Lattice {version} is not pinned in the manifest.")
    if version == current_version(root):
        say(f"already on Lattice {version}.")
        return
    stage_release(root, manifest["releases"][version])
    switch_to(root, version, start=not args.no_start, entry=manifest["releases"][version])
    prune(root)


def cmd_rollback(args: argparse.Namespace) -> None:
    root: Path = args.root
    previous = root / "previous"
    if not previous.is_symlink():
        raise HostError("there is no previous release to go back to.")
    version = Path(os.readlink(previous)).name
    entry = json.loads((root / "releases" / version / "release.json").read_text())
    switch_to(root, version, start=not args.no_start, entry=entry)


