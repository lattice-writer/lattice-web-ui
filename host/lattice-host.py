def find_x11vnc(root: Path) -> tuple[str, str | None]:
    """x11vnc shows the host's hidden display over VNC. Unpacked without root if missing."""
    system = shutil.which("x11vnc")
    if system:
        return system, None
    target = root / "vnc"
    binary = target / "usr/bin/x11vnc"
    if not binary.is_file():
        with tempfile.TemporaryDirectory() as temp:
            subprocess.run(["apt", "download", "x11vnc", "libvncserver1"], cwd=temp, check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            target.mkdir(parents=True, exist_ok=True)
            for deb in glob.glob(f"{temp}/*.deb"):
                subprocess.run(["dpkg", "-x", deb, str(target)], check=True)
    return str(binary), str(target / "usr/lib/x86_64-linux-gnu")


def cmd_overleaf_login(args: argparse.Namespace) -> None:
    """Sign Lattice in to Overleaf on the host itself, never from a browser device.

    Lattice opens Overleaf's sign-in as a native window on the host's hidden
    display. This shows that display over VNC on 127.0.0.1 only, for one
    session, behind a one-time password; reach it through an SSH tunnel.
    """
    root: Path = args.root
    config = read_config(root)
    binary, libs = find_x11vnc(root)
    password = hashlib.sha256(os.urandom(32)).hexdigest()[:8]  # VNC passwords are 8 characters
    with tempfile.TemporaryDirectory(dir=root) as temp:
        auth = Path(temp) / "vnc.pass"
        env = dict(os.environ, **({"LD_LIBRARY_PATH": libs} if libs else {}))
        subprocess.run([binary, "-storepasswd", password, str(auth)], check=True, env=env,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        auth.chmod(0o600)
        host = os.uname().nodename
        say("The host's display is shared on 127.0.0.1:%d until you disconnect (at most 30 minutes)." % args.port)
        say(f"1. On your Mac: ssh -N -L {args.port}:127.0.0.1:{args.port} {os.environ.get('USER', 'you')}@{host}")
        say(f"2. Open vnc://localhost:{args.port} in Finder > Go > Connect to Server (Screen Sharing). Password: {password}")
        say("3. In the workspace choose Open from Overleaf > Connect to Overleaf. Sign in in the window that appears.")
        say("4. Disconnect Screen Sharing when Lattice shows your Overleaf projects.")
        command = [binary, "-display", f":{config['display']}", "-localhost", "-rfbport", str(args.port),
                   "-rfbauth", str(auth), "-once", "-nopw", "-quiet", "-noxdamage", "-shared"]
        try:
            subprocess.run(["timeout", "1800", *command], env=env, check=False)
        except KeyboardInterrupt:
            pass
    say("Display sharing stopped.")


def cmd_uninstall(args: argparse.Namespace) -> None:
    systemctl("disable", "--now", *UNITS, *UPDATE_UNITS, check=False)
    for unit in (*UNITS, *UPDATE_FILES):
        (UNIT_DIR / unit).unlink(missing_ok=True)
    systemctl("daemon-reload", check=False)
    if args.purge:
        shutil.rmtree(args.root, ignore_errors=True)
        say(f"removed the services and {args.root}.")
    else:
        say(f"removed the services. Releases, paired devices and the token stay in {args.root} (use --purge to delete them).")


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="lattice-host", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", type=Path, default=DEFAULT_ROOT, help=f"host directory (default {DEFAULT_ROOT})")
    sub = p.add_subparsers(dest="command", required=True)

    install = sub.add_parser("install", help="install a pinned Lattice release and start it")
    install.add_argument("--public-origin", required=True, help="HTTPS origin browsers will use")
    install.add_argument("--version", help="Lattice version from the manifest (default: its pinned default)")
    install.add_argument("--manifest", type=Path, default=KIT / "lattice-releases.json")
    install.add_argument("--gateway-binary")
    install.add_argument("--gateway-port", type=int, default=18490)
    install.add_argument("--display", type=int, default=99)
    install.add_argument("--xvfb", help="path to Xvfb")
    install.add_argument("--fetch-xvfb", action="store_true", help="unpack Ubuntu's xvfb into the host directory (no sudo)")
    install.add_argument("--agent-origin", help="second HTTPS origin (same host, another port) for Lattice's Agent; "
                         "served by the gateway on --gateway-port + 1")
    install.add_argument("--projects-root", help="folder whose subfolders the gateway's Projects page offers to open")
    install.add_argument("--home", help="HOME for Lattice (default: yours, so agent CLIs keep their sign-in)")
    install.add_argument("--tailscale", action="store_true",
                         help="serve through Tailscale Serve/Funnel sockets: the owner's tailnet login needs no sign-in")
    install.add_argument("--owner-login", action="append", help="Tailscale login that is the owner (repeatable)")
    install.add_argument("--ingress-uid", type=int, help="UID of a containerized tailscaled allowed on the sockets")
    install.add_argument("--no-start", action="store_true")
    install.set_defaults(func=cmd_install)

    update = sub.add_parser("update", help="move to another pinned Lattice release; rolls back if it fails to start")
    update.add_argument("--to")
    update.add_argument("--manifest")
    update.add_argument("--gateway-binary")
    update.add_argument("--no-start", action="store_true")
    update.set_defaults(func=cmd_update)

    rollback = sub.add_parser("rollback", help="go back to the previous release")
    rollback.add_argument("--no-start", action="store_true")
    rollback.set_defaults(func=cmd_rollback)

    sub.add_parser("status", help="show the release and service state").set_defaults(func=cmd_status)

    sub.add_parser("phone", help="show the workspace address as a QR code to open on a phone").set_defaults(func=cmd_phone)
    sub.add_parser("check-update", help="look for a newer stable lattice-web-ui release (run by a timer)").set_defaults(func=cmd_check_update)
    self_update = sub.add_parser("self-update", help="update to the release the owner chose in the browser (run by a path unit)")
    self_update.add_argument("--to", help="version to update to (default: the one the owner requested)")
    self_update.add_argument("--wait", type=int, default=90, help="seconds to wait for the new gateway")
    self_update.set_defaults(func=cmd_self_update)

    overleaf = sub.add_parser("overleaf-login", help="sign Lattice in to Overleaf on the host, through a one-time VNC session")
    overleaf.add_argument("--port", type=int, default=5999)
    overleaf.set_defaults(func=cmd_overleaf_login)

    uninstall = sub.add_parser("uninstall", help="stop and remove the services")
    uninstall.add_argument("--purge", action="store_true", help="also delete releases, paired devices and the token")
    uninstall.set_defaults(func=cmd_uninstall)
    return p


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        args.func(args)
    except HostError as error:
        print(f"lattice-host: {error}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as error:
        detail = (error.stderr or "").strip() if isinstance(error.stderr, str) else ""
        print(f"lattice-host: {' '.join(map(str, error.cmd))} failed ({error.returncode}). {detail}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
